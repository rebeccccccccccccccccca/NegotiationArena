import re

from negotiationarena.agents.chatgpt import ChatGPTAgent
from negotiationarena.constants import (
    MONEY_TOKEN,
    AGENT_ONE,
    AGENT_TWO,
    PLAYER_ANSWER_TAG,
    PROPOSED_TRADE_TAG,
    PROPOSAL_COUNT_TAG,
    RESOURCES_TAG,
    GOALS_TAG,
    REASONING_TAG,
    MESSAGE_TAG,
)


SCRIPTED_MESSAGE_TEMPLATES = {
    "en": "I am offering the object for {price} {money}.",
    "zh": "我以 {price} {money} 出售這件物品。",
}

# The scripted turn stays in the seller's own history as if the seller had
# written it, so its private fields read like an ordinary turn in the
# game's language and say nothing about being scripted: a note there that
# the offer was fixed by the experiment would tell the seller it is being
# tested, and in English it would also put a language switch into every
# Chinese seller's history but no English one.
SCRIPTED_REASON_TEMPLATES = {
    "en": "I will open with this price.",
    "zh": "我以這個價格作為開價。",
}
GOALS_RE = re.compile(rf"<{GOALS_TAG}>(.*?)</{GOALS_TAG}>", re.S)


class FixedFirstOfferSellerAgent(ChatGPTAgent):
    """
    A ChatGPTAgent whose opening offer is fixed by the experimenter instead
    of generated by the model, so the negotiation's starting anchor is
    controlled directly. Only the very first `chat()` call is scripted (no
    API call is made for it); every later call is a normal API call, so the
    seller's strategy from its second move onward is still the model's own.
    That the opening was scripted is recorded by the runner (game_state.json
    `experiment`), not in the turn itself.
    """

    def __init__(
        self,
        first_offer,
        resource_name="X",
        resource_amount=1,
        language="en",
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.first_offer = first_offer
        self.resource_name = resource_name
        self.resource_amount = resource_amount
        self.language = language
        self.used_scripted_offer = False

    def chat(self):
        if not self.used_scripted_offer:
            self.used_scripted_offer = True
            return self._scripted_first_offer()
        return super().chat()

    def _own_goal_text(self):
        """The goal sentence in the seller's system prompt: what the model
        itself writes back in <my goals> on its later turns."""
        system = next(m["content"] for m in self.conversation if m["role"] == "system")
        match = GOALS_RE.search(system)
        return match.group(1).strip() if match else ""

    def _scripted_first_offer(self):
        message = SCRIPTED_MESSAGE_TEMPLATES[self.language].format(
            price=self.first_offer, money=MONEY_TOKEN
        )
        return (
            f"<{PROPOSAL_COUNT_TAG}> 1 </{PROPOSAL_COUNT_TAG}>\n"
            f"<{RESOURCES_TAG}> {self.resource_name}: {self.resource_amount} </{RESOURCES_TAG}>\n"
            f"<{GOALS_TAG}> {self._own_goal_text()} </{GOALS_TAG}>\n"
            f"<{REASONING_TAG}> {SCRIPTED_REASON_TEMPLATES[self.language]} </{REASONING_TAG}>\n"
            f"<{PLAYER_ANSWER_TAG}> PROPOSAL </{PLAYER_ANSWER_TAG}>\n"
            f"<{PROPOSED_TRADE_TAG}> {AGENT_ONE} Gives {self.resource_name}: {self.resource_amount} | "
            f"{AGENT_TWO} Gives {MONEY_TOKEN}: {self.first_offer} </{PROPOSED_TRADE_TAG}>\n"
            f"<{MESSAGE_TAG}> {message} </{MESSAGE_TAG}>"
        )
